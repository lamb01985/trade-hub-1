import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'

const origin = 'http://127.0.0.1:4180'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
const page = await context.newPage()
const failures = []
page.on('pageerror', error => failures.push(error.message))
try {
  await page.goto(`${origin}/?intelligence=map`)
  await page.getByText('FRIDAY-CLOSE SNAPSHOT · LOCAL SAMPLE · NOT LIVE', { exact: true }).waitFor()
  const intel = page.getByRole('region', { name: 'Market Intelligence' })
  await intel.getByRole('heading', { name: 'QQQ', exact: true }).waitFor()
  await intel.getByText('704.4', { exact: true }).waitFor()
  await fs.mkdir('.local', { recursive: true })
  await page.screenshot({ path: '.local/market-map-desktop.png', fullPage: true })
  await intel.getByRole('button', { name: 'Options Positioning', exact: true }).click()
  await intel.getByRole('heading', { name: 'QQQ positioning' }).waitFor()
  assert(await intel.getByText('67,245', { exact: true }).count() > 0)
  await intel.getByRole('button', { name: 'SPY', exact: true }).click()
  await intel.getByRole('heading', { name: 'SPY positioning' }).waitFor()
  assert(await intel.getByText('292,006', { exact: true }).count() > 0)
  await page.screenshot({ path: '.local/options-positioning-desktop.png', fullPage: true })
  await intel.getByRole('button', { name: 'Intraday Playbook', exact: true }).click()
  await intel.getByText('759.14', { exact: true }).first().waitFor()
  await intel.getByRole('button', { name: 'Swing Playbook', exact: true }).click()
  await intel.getByText(/unvalidated swing hypotheses/).waitFor()
  // Existing workspace buttons remain navigable without replacing the cockpit.
  await page.getByRole('button', { name: /Trade Live session workspace/i }).click()
  await page.getByRole('button', { name: /Review Post-market log/i }).click()
  await page.getByRole('button', { name: /Plan Pre-market game plan/i }).click()
  await page.getByRole('button', { name: 'Market Intelligence', exact: true }).click()
  await intel.getByRole('button', { name: 'Market Map', exact: true }).click()
  const journalBefore = await page.evaluate(() => localStorage.getItem('th-trades'))
  await intel.getByRole('button', { name: 'Analyst Brief', exact: true }).click()
  await intel.getByText('Evidence, assumptions and research scenarios', {exact:true}).click()
  await intel.getByRole('heading', { name: /QQQ: mixed daily/ }).waitFor()
  await intel.getByRole('button', { name: 'SPY', exact: true }).click()
  await intel.getByRole('heading', { name: /SPY: mixed daily/ }).waitFor()
  await intel.getByText(/OI changes are unavailable/).waitFor()
  await intel.getByLabel('I reviewed risk and the stand-aside conditions').check()
  await intel.getByText('NOT READY: historical sample and missing current confirmation.', { exact: true }).waitFor()
  await intel.getByRole('button', { name: 'Save bullish hypothesis', exact: true }).click()
  for (const label of ['Your hypothesis','Strongest counterargument','What would invalidate the case','Risk assumptions, costs and maximum loss']) await intel.getByLabel(label,{exact:true}).fill('Dated evidence, explicit risk limits and a falsifiable competing explanation.')
  await intel.getByRole('button',{name:'Save research plan',exact:true}).click()
  await intel.getByText(/Research hypothesis saved separately/).waitFor()
  await page.screenshot({ path: '.local/analyst-brief-desktop.png', fullPage: true })
  await intel.getByRole('button', { name: 'Review hypothetical outcomes', exact: true }).click()
  await page.getByRole('region', { name: 'Research outcomes' }).getByText('Outcome pending. No result is inferred.', { exact: true }).waitFor()
  assert.equal(await page.evaluate(() => localStorage.getItem('th-trades')), journalBefore)
  await page.reload()
  await page.getByText('FRIDAY-CLOSE SNAPSHOT · LOCAL SAMPLE · NOT LIVE', { exact: true }).waitFor()
  await page.getByRole('button', { name: /Review Post-market log/i }).click()
  await page.getByRole('button', { name: 'Research outcomes', exact: true }).click()
  await page.getByText('Outcome pending. No result is inferred.', { exact: true }).waitFor()
  await page.getByRole('button', { name: /Plan Pre-market game plan/i }).click()
  await page.getByRole('button', { name: 'Market Intelligence', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  for (const label of ['Analyst Brief', 'Training Mode', 'Market Map', 'Options Positioning', 'Intraday Playbook', 'Swing Playbook']) {
    await intel.getByRole('button', { name: label, exact: true }).click()
    await intel.getByRole('heading', { name: label, exact: true }).waitFor()
    const overflow = await intel.evaluate(el => el.scrollWidth > el.clientWidth + 1)
    assert.equal(overflow, false, `${label} overflows mobile container`)
  }
  await intel.getByRole('button', { name: 'Market Map', exact: true }).click()
  await page.screenshot({ path: '.local/market-map-mobile.png', fullPage: true })
  const unauthenticated = await browser.newContext()
  const denied = await unauthenticated.request.get(`${origin}/api/intelligence/latest`)
  assert.equal(denied.status(), 401)
  const privateFile = await context.request.get(`${origin}/private-reports/october-26.json`)
  assert.equal(privateFile.status(), 403)
  assert(!await privateFile.text().then(t => t.includes('705.0')))
  assert.deepEqual(failures, [], 'Browser runtime errors')
  console.log('PASS: analyst QQQ/SPY examples, research persistence across reload, actual journal isolation, all five views, QQQ/SPY options, Plan/Trade/Review navigation, mobile containment, anonymous API denial and private-file denial.')
} finally { await context.close(); await browser.close() }
